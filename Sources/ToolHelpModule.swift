struct ToolHelpView: View {
    let item: ToolItem
    var body: some View {
        List {
            Section { Text(item.desc.scriptConverted).font(.body).lineSpacing(5) }
            let notes = ToolHelpContent.entries[item.id] ?? []
            ForEach(Array(notes.enumerated()), id: \.offset) { index, note in
                Section {
                    Text(note.scriptConverted).font(.body).lineSpacing(6).textSelection(.enabled)
                } header: {
                    Text(["使用前准备", "操作与阅读顺序", "如何理解结果与限制"][min(index, 2)])
                }
            }
        }
        .navigationTitle(item.title.scriptConverted)
        .navigationBarTitleDisplayMode(.inline)
    }
}
