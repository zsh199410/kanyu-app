    /// 简体文本 → 繁体文本：长词优先替换，幂等（繁体侧字符不在 key 中）。
    static func convert(_ text: String) -> String {
        var out = text
        let keys = terms.keys.sorted { a, b in
            if a.count != b.count {
                return a.count > b.count
            }
            return a < b
        }
        for key in keys {
            if let value = terms[key] {
                out = out.replacingOccurrences(of: key, with: value)
            }
        }
        return out
    }

    /// 按当前脚本转换；简体原样返回。
    static func convert(_ text: String, for script: KanyuScript) -> String {
        if script == .hant {
            return convert(text)
        }
        return text
    }
}

extension String {
    /// 按当前存储的脚本转换（默认简体，原样返回）。
    var scriptConverted: String {
        ZhHantTerms.convert(self, for: KanyuScript.stored)
    }

    /// 按指定脚本转换。
    func converted(for script: KanyuScript) -> String {
        ZhHantTerms.convert(self, for: script)
    }
}

