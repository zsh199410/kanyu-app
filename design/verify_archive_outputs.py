#!/usr/bin/env python3
"""Validate durable PDFs produced by the unchanged XCTest suite on the macOS runner."""
import hashlib
import json
import shutil
from pathlib import Path

simulators = Path.home() / 'Library/Developer/CoreSimulator/Devices'
files = list(simulators.glob('*/data/Containers/Data/Application/*/Documents/KanyuExports/*/命书-*.pdf'))
assert len(files) >= 3, 'Expected durable PDFs generated by the existing concise/professional/complete report tests'
expected_tiers = {'简洁', '专业', '完整'}
found_tiers = {tier for file in files for tier in expected_tiers if '-'+tier+'-' in file.name}
assert found_tiers == expected_tiers, f'Missing archive tiers: {expected_tiers - found_tiers}'
# One XCTest run can export the same tier twice (e.g. two fixture persons), but
# the next step requires exactly one PDF per tier, so keep only the latest file
# per tier by modification time (file name breaks ties, so the choice is
# deterministic) and log every file dropped. The kept file still passes through
# the same PDF-signature, archive-digest and content-hash checks below; this
# only fixes the count, it does not weaken verification.
kept = []
dropped = []
for tier in sorted(expected_tiers):
    candidates = sorted((f for f in files if '-'+tier+'-' in f.name),
                        key=lambda f: (f.stat().st_mtime_ns, f.name))
    kept.append(candidates[-1])
    for stale in candidates[:-1]:
        dropped.append({'file': stale.name, 'tier': tier,
                        'sha256': hashlib.sha256(stale.read_bytes()).hexdigest(),
                        'mtime_ns': stale.stat().st_mtime_ns})
        print(f'DEDUP: dropped stale {tier} PDF {stale.name} (kept {candidates[-1].name})')
files = list(dict.fromkeys(kept))
samples = Path('build/report-samples')
samples.mkdir(parents=True, exist_ok=True)
records = []
for file in files:
    data = file.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    assert data.startswith(b'%PDF-'), f'Invalid PDF signature: {file.name}'
    assert file.parent.name == digest, f'Archive content digest mismatch: {file.name}'
    target = samples / (digest[:12]+'-'+file.name)
    shutil.copyfile(file, target)
    records.append({'file': target.name, 'bytes': len(data), 'sha256': digest})
Path('build/archive-verification.json').write_text(json.dumps({'scope': 'actual PDFs produced by existing XCTest on simulator; not all poster styles or device testing', 'tiers': sorted(found_tiers), 'files': records, 'dropped': dropped}, ensure_ascii=False, indent=2)+'\n')
print(f'PASS: {len(records)} durable PDFs, all 3 tiers, PDF signatures and archive SHA256 checked' + (f'; dropped {len(dropped)} stale duplicate(s)' if dropped else ''))
